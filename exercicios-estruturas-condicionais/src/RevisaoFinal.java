
public class RevisaoFinal {

	public static void main(String[] args) {

		String frase = " JAVA é muito legal ";
		
		System.out.println(frase.toLowerCase());
		System.out.println(frase.toUpperCase());
		System.out.println(frase.trim());
		System.out.println(frase.substring(1, 5));
		System.out.println(frase.replace("JAVA", "Python"));
		System.out.println(frase.indexOf("muito"));
		System.out.println(frase.split(" "));
		
	}

}
